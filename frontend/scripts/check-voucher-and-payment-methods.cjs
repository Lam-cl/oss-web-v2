const assert=require('node:assert/strict');
const {parse,find,ts}=require('./test-source-helpers.cjs');
const tree=parse('src/app/api/bundle/checkout/route.ts');
const allowlist=find(tree,n=>ts.isCallExpression(n)&&ts.isPropertyAccessExpression(n.expression)&&n.expression.name.text==='includes'&&n.arguments[0]?.getText(tree)==='paymentMethodId')[0];
assert(allowlist,'Server must validate payment methods');
const expr=allowlist.getText(tree);
for(const [value,wanted] of [['16',true],['2',true],['3',true],['',false],['99',false],['16,2',false]])assert.equal(new Function('paymentMethodId','return '+expr)(value),wanted);
const form=parse('src/app/checkout/page.tsx');
assert.deepEqual(find(form,n=>ts.isCallExpression(n)&&n.expression.getText(form)==='setPaymentMethodId').map(n=>n.arguments[0]?.text).filter(Boolean).sort(),['16','2','3']);
const admin=parse('src/app/admin/vouchers/page.tsx');
const methods=find(admin,n=>ts.isPropertyAssignment(n)&&n.name.getText(admin)==='method').map(n=>n.initializer.text);
assert(methods.includes('DELETE')&&methods.includes('PATCH'));
assert(find(tree,n=>ts.isShorthandPropertyAssignment(n)&&n.name.text==='paymentMethodId').length,'Payment method is forwarded');
console.log('Payment method allowlist behavior and voucher mutation methods passed');
