const assert = require('node:assert/strict');
const fs = require('node:fs');
const drawer = fs.readFileSync('/www/wwwroot/tonewow.xifuhalim.com/src/components/admin/ProductDrawer.tsx', 'utf8');
assert(!drawer.includes('editOptionName'), 'option name must not be editable while adding values');
assert(drawer.includes('Edit option values'), 'safe option-value editor heading missing');
assert(drawer.includes('name: selectedOption.name'), 'option update must preserve the selected option name');
assert(drawer.includes('Add a value here'), 'add/remove value guidance missing');
assert(drawer.includes('hiddenOptionValueIds'), 'drawer must hide removed Bundle option values locally');
assert(drawer.includes('Remove the selected value'), 'single-option value removal needs explicit confirmation');
assert(drawer.includes('products/${fresh.id}/hidden-option-values'), 'drawer must persist hidden option values');
const repair = fs.readFileSync('/www/wwwroot/tonewow.xifuhalim.com/src/lib/admin/productSetup.server.ts', 'utf8');
const repairSection = repair.slice(repair.indexOf('export async function repairProductVariants'));
assert(repairSection.includes('readProductHiddenOptionValues'), 'variant repair must ignore locally hidden values');
assert(!repairSection.includes("method: 'DELETE'"), 'repair must not delete the option value before creating its variant');
assert(repairSection.includes('values: missing.map'), 'repair must create variants from the missing values');
assert(repairSection.includes('defaultInventory: 0'), 'new option values must start sold out until admin sets stock');
assert(repairSection.includes('batch-update'), 'new variants must receive canonical product price after creation');
assert(repairSection.includes('price: Number(product.price)'), 'new variant price must match the product price');
console.log('Admin option value editor check passed');
