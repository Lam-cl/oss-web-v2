const assert=require('node:assert/strict');
const {parse,elements,text,find,ts}=require('./test-source-helpers.cjs');
const tree=parse('src/components/admin/OrderDrawer.tsx');
assert(elements(tree,'small').some(n=>text(n)==='NRIC / Passport'));
assert(elements(tree,'strong').some(n=>find(n,x=>ts.isCallExpression(x)&&x.expression.getText(tree)==='orderCustomerId').length), 'Customer ID is rendered read-only');
const labels=elements(tree,'label').map(text);
for(const label of ['Tracking number','Delivery option','Courier service']) assert(labels.some(value=>value.includes(label)),label);
assert(!labels.some(value=>/IMEI|NRIC|Passport/.test(value)),'Identity must not be editable');
const billing=elements(tree,'section').find(n=>elements(n,'h3').some(h=>text(h)==='Billing Address')&&!elements(n,'section').some(s=>s!==n));
assert(billing);
let parent=billing.parent;while(parent&&!ts.isBinaryExpression(parent))parent=parent.parent;
assert(parent&&parent.operatorToken.kind===ts.SyntaxKind.AmpersandAmpersandToken&&parent.left.getText(tree)==='pickup','Billing is pickup-only');
assert(elements(tree,'button').some(n=>find(n,x=>ts.isStringLiteral(x)&&x.text==='Save').length),'Courier save action remains visible');
require('./test-courier-behavior.cjs')().then(()=>console.log('Read-only identity, delivery fields, pickup billing and courier payload passed')).catch(e=>{console.error(e);process.exitCode=1;});
